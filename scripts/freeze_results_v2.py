"""Compute SHA-256 manifest for results-freeze-v2 artifacts.

Inputs are the artifacts produced by the four peer-review revisions:
- results/raw_templated/a_templated.jsonl
- results/raw_noretrieval/n.jsonl
- results/scored_templated/{scored,recall_at_k,latency_tokens}.csv
- results/scored_noretrieval/{scored,recall_at_k,latency_tokens}.csv
- features/results.csv and features/results_aggregate.csv (class-weighted re-run)
- analysis/tier3_recall_breakdown.md
- analysis/templated_compare.md
- analysis/lightgbm_class_weight_comparison.md
- analysis/latency_tokens.md (updated with cost-per-correct)
- analysis/feature_extraction.md (regenerated by feature-arm re-run)

Output: data/freeze_v2.json with per-file SHA-256 hashes and an overall
manifest hash.

Usage::

    C:/ProgramData/miniconda3/envs/ml/python.exe scripts/freeze_results_v2.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Paths relative to ROOT.
TRACKED: list[str] = [
    "results/raw_templated/a_templated.jsonl",
    "results/raw_noretrieval/n.jsonl",
    "results/scored_templated/scored.csv",
    "results/scored_templated/recall_at_k.csv",
    "results/scored_templated/latency_tokens.csv",
    "results/scored_noretrieval/scored.csv",
    "results/scored_noretrieval/recall_at_k.csv",
    "results/scored_noretrieval/latency_tokens.csv",
    "features/results.csv",
    "features/results_aggregate.csv",
    "features/labels.csv",
    "features/fs_structured.parquet",
    "features/fs_narrative.parquet",
    "features/fs_aware.parquet",
    "features/FEATURES.md",
    "analysis/tier3_recall_breakdown.md",
    "analysis/templated_compare.md",
    "analysis/lightgbm_class_weight_comparison.md",
    "analysis/feature_extraction.md",
    "analysis/latency_tokens.md",
]


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    entries: dict[str, dict] = {}
    missing: list[str] = []
    for rel in TRACKED:
        p = ROOT / rel
        if not p.exists():
            missing.append(rel)
            continue
        entries[rel] = {
            "sha256": sha256_of(p),
            "size_bytes": p.stat().st_size,
        }
    if missing:
        print(f"WARNING: {len(missing)} tracked file(s) missing:")
        for m in missing:
            print(f"  - {m}")

    # Overall manifest hash: SHA-256 over a canonical JSON of (path, sha256)
    # pairs sorted by path. Deterministic across reruns.
    canonical = json.dumps(
        sorted([(k, v["sha256"]) for k, v in entries.items()]),
        sort_keys=False,
        ensure_ascii=False,
    )
    overall = hashlib.sha256(canonical.encode("utf-8")).hexdigest()

    out = {
        "freeze_tag": "results-freeze-v2",
        "n_files": len(entries),
        "missing_files": missing,
        "overall_sha256": overall,
        "files": entries,
    }
    out_path = ROOT / "data" / "freeze_v2.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {out_path}")
    print(f"  files: {len(entries)}")
    print(f"  missing: {len(missing)}")
    print(f"  overall SHA-256: {overall}")


if __name__ == "__main__":
    main()
